export function getPrimeLocale(locale) {
    const base = structuredClone(defaultOptions.locale)
    const dateNames = (count, options, month) =>
        Array.from({ length: count }, (_, index) =>
            new Intl.DateTimeFormat(locale, options).format(
                new Date(2026, month ? index : 0, month ? 1 : 4 + index)
            )
        )
    return {
        ...base,
        ...structuredClone(primeTranslations[locale] || {}),
        dayNames: dateNames(7, { weekday: 'long' }, false),
        dayNamesShort: dateNames(7, { weekday: 'short' }, false),
        dayNamesMin: dateNames(7, { weekday: 'narrow' }, false),
        monthNames: dateNames(12, { month: 'long' }, true),
        monthNamesShort: dateNames(12, { month: 'short' }, true)
    }
}
